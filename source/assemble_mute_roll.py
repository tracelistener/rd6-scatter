"""Assemble source/mute_roll.py's SOURCE and store the bytes in its generated section.

Development only: needs keystone (`pip install keystone-engine`) as well as capstone.
Building and checking the firmware use only the stored bytes.

Keystone sometimes encodes a b.w or bl to an absolute address 2 bytes off, and an
out-of-range cbz without an error. Absolute b.w and bl are therefore re-encoded with
mute_roll.branch(), and every branch, adr and data table is checked against the
listing with mute_roll.check_branches(); any other mismatch stops the run.
"""
import importlib.util, re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.dont_write_bytecode = True   # mute_roll.py is rewritten below, often at the same size
import mute_roll as M
from keystone import Ks, KS_ARCH_ARM, KS_MODE_THUMB
from capstone import Cs, CS_ARCH_ARM, CS_MODE_THUMB


def assemble(name, base):
    ks = Ks(KS_ARCH_ARM, KS_MODE_THUMB)
    code = bytearray(ks.asm('.arch armv7e-m\n' + M.SOURCE[name], base)[0])
    instrs, _ = M.parse(M.SOURCE[name])
    md = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    for (_, mnemonic, operands), ins in zip(instrs, list(md.disasm(bytes(code), base, len(instrs)))):
        if mnemonic in ('b.w', 'bl') and operands.startswith('0x'):
            at = ins.address - base
            code[at:at + 4] = M.branch(ins.address, int(operands, 16), link=mnemonic == 'bl')
    problems = M.check_branches(name, base, bytes(code))
    if problems: raise SystemExit('\n'.join(problems))
    return bytes(code)


def main():
    at, address, body = M.START, {}, {}
    for name in M.ORDER:
        code = assemble(name, at)
        address[name], body[name] = at, code
        at = (at + len(code) + 3) & ~3
    lines = ['# --- generated by source/assemble_mute_roll.py: do not edit by hand ---',
             'ADDRESS = {' + ', '.join(f"'{n}': {a:#010x}" for n, a in address.items()) + '}',
             'BODY = {']
    for name, code in body.items():
        hexed = code.hex()
        chunks = [hexed[i:i + 96] for i in range(0, len(hexed), 96)]
        lines.append(f"    '{name}': bytes.fromhex(")
        lines += [f"        '{c}'" for c in chunks[:-1]] + [f"        '{chunks[-1]}'),"]
    lines += ['}', '# --- end of generated section ---']
    path = HERE / 'mute_roll.py'
    text = path.read_bytes().decode()
    pattern = r'# --- generated by source/assemble_mute_roll\.py.*?# --- end of generated section ---'
    new, count = re.subn(pattern, lambda _: '\n'.join(lines), text, flags=re.S)
    assert count == 1
    path.write_bytes(new.encode())
    Path(importlib.util.cache_from_source(str(path))).unlink(missing_ok=True)   # never let a stale .pyc win
    for name in M.ORDER: print(f'{name:9s} {address[name]:#010x} {len(body[name])} bytes')
    print(f'end       {at:#010x}')


if __name__ == '__main__': main()
